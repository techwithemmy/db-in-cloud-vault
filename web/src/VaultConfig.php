<?php
declare(strict_types=1);

/**
 * Reads/writes vault settings. Prefer data/config.php (created by web setup).
 */
final class VaultConfig
{
    public static function path(): string
    {
        $data = dirname(__DIR__) . '/data/config.php';
        if (is_file($data)) {
            return $data;
        }
        $legacy = dirname(__DIR__) . '/config.php';
        return is_file($legacy) ? $legacy : $data;
    }

    public static function exists(): bool
    {
        return is_file(self::path());
    }

    /** @return array<string,mixed> */
    public static function load(): array
    {
        $path = self::path();
        if (!is_file($path)) {
            return [];
        }
        $loaded = require $path;
        return is_array($loaded) ? self::normalize($loaded) : [];
    }

    /**
     * @param array<string,mixed> $config
     * @throws RuntimeException
     */
    public static function save(array $config): void
    {
        $dir = dirname(__DIR__) . '/data';
        if (!is_dir($dir) && !mkdir($dir, 0750, true) && !is_dir($dir)) {
            throw new RuntimeException('Cannot create data/ directory. Make it writable.');
        }
        if (!is_writable($dir)) {
            throw new RuntimeException('data/ is not writable by PHP. chmod 750 and chown the web user.');
        }

        $config = self::normalize($config);
        $export = var_export($config, true);
        $php = "<?php\n/** Auto-generated by Backup Vault setup. Do not commit. */\ndeclare(strict_types=1);\n\nreturn " . $export . ";\n";
        $target = $dir . '/config.php';
        $tmp = $target . '.tmp.' . bin2hex(random_bytes(4));
        if (file_put_contents($tmp, $php) === false) {
            throw new RuntimeException('Could not write config file.');
        }
        if (!rename($tmp, $target)) {
            @unlink($tmp);
            throw new RuntimeException('Could not finalize config file.');
        }
        @chmod($target, 0640);
    }

    /** @param array<string,mixed> $raw @return array<string,mixed> */
    public static function normalize(array $raw): array
    {
        $provider = (string) ($raw['storage_provider'] ?? 'cloudflare');
        if ($provider === 'cloudflare_r2') {
            $provider = 'cloudflare';
        }
        $provider = StorageProviders::sanitize($provider);

        $passwordHash = trim((string) ($raw['portal_password_hash'] ?? ''));
        $password = (string) ($raw['portal_password'] ?? '');
        if ($passwordHash === '' && $password !== '' && !str_starts_with($password, '$2y$')) {
            $passwordHash = password_hash($password, PASSWORD_DEFAULT);
            $password = '';
        }

        $cronKeys = [];
        if (!empty($raw['cron_key'])) {
            $cronKeys[] = trim((string) $raw['cron_key']);
        }
        if (is_array($raw['cron_keys'] ?? null)) {
            foreach ($raw['cron_keys'] as $k) {
                $cronKeys[] = trim((string) $k);
            }
        }
        if (is_string($raw['encryption_keys_text'] ?? null) || is_string($raw['cron_keys_text'] ?? null)) {
            $text = (string) ($raw['encryption_keys_text'] ?? $raw['cron_keys_text'] ?? '');
            foreach (preg_split('/[\r\n,]+/', $text) ?: [] as $k) {
                $cronKeys[] = trim($k);
            }
        }
        $cronKeys = array_values(array_unique(array_filter(
            $cronKeys,
            static fn(string $k): bool => $k !== '' && !str_contains($k, 'paste-')
        )));

        $productName = trim((string) ($raw['product_name'] ?? 'Backup Vault'));
        if ($productName === '') {
            $productName = 'Backup Vault';
        }

        $pick = static function (array $raw, array $keys): string {
            foreach ($keys as $key) {
                if (!array_key_exists($key, $raw)) {
                    continue;
                }
                $v = trim((string) $raw[$key]);
                if ($v !== '') {
                    return $v;
                }
            }
            return '';
        };

        $pathStyle = true;
        if (array_key_exists('storage_path_style', $raw)) {
            $pathStyle = (bool) $raw['storage_path_style'];
        } elseif (array_key_exists('s3_path_style', $raw)) {
            $pathStyle = (bool) $raw['s3_path_style'];
        } else {
            $pathStyle = (bool) (StorageProviders::all()[$provider]['path_style'] ?? true);
        }

        return [
            'product_name' => $productName,
            'portal_password_hash' => $passwordHash,
            'portal_password' => $password,
            'storage_provider' => $provider,
            'storage_endpoint' => $pick($raw, ['storage_endpoint', 's3_endpoint', 'r2_endpoint']),
            'storage_region' => $pick($raw, ['storage_region', 's3_region']) ?: 'auto',
            'storage_bucket' => $pick($raw, ['storage_bucket', 's3_bucket', 'r2_bucket']),
            'storage_public_url' => rtrim($pick($raw, ['storage_public_url', 's3_public_url', 'r2_url']), '/'),
            'storage_access_key' => $pick($raw, ['storage_access_key', 's3_access_key_id', 'r2_access_key_id']),
            'storage_secret_key' => $pick($raw, ['storage_secret_key', 's3_secret_access_key', 'r2_secret_access_key']),
            'storage_path_style' => $pathStyle,
            'encryption_keys' => $cronKeys,
            'cron_keys' => $cronKeys, // alias for VaultClient
            'sites' => is_array($raw['sites'] ?? null) ? $raw['sites'] : [],
            'setup_complete' => !empty($raw['setup_complete']),
        ];
    }

    /** @param array<string,mixed> $config */
    public static function isConfigured(array $config): bool
    {
        if (empty($config)) {
            return false;
        }
        $hasPass = trim((string) ($config['portal_password_hash'] ?? '')) !== ''
            || trim((string) ($config['portal_password'] ?? '')) !== '';
        $hasStorage = trim((string) ($config['storage_endpoint'] ?? '')) !== ''
            && trim((string) ($config['storage_bucket'] ?? '')) !== ''
            && trim((string) ($config['storage_access_key'] ?? '')) !== ''
            && trim((string) ($config['storage_secret_key'] ?? '')) !== '';
        $keys = $config['encryption_keys'] ?? $config['cron_keys'] ?? [];
        $hasKeys = is_array($keys) && $keys !== [];
        return $hasPass && $hasStorage && $hasKeys;
    }
}
